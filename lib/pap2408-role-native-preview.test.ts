import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createNativeRolePreview,ROLE_LOCAL_MARKER} from "../app/ho/system/roles/role-native-preview-boundary";
import {roleQuery} from "../app/ho/system/roles/schema";
import {createRoleMetadataClient} from "../app/ho/system/roles/role-metadata-flow";
import {rolePreviewCatalog} from "../app/ho/system/roles/role-m1-preview";
test("PAP-2408 local-only exact native adapter, one seed, independently isolated",async()=>{
 const a=createNativeRolePreview(),b=createNativeRolePreview(true),signal=new AbortController().signal;
 const list=await a.ready.adapter.list(roleQuery,signal);
 assert.equal(list.rows.length,1);assert.match(String(list.rows[0].description),new RegExp(ROLE_LOCAL_MARKER));
 assert.equal(b.ready.navigation.read().kind,"drawer");
 assert.equal(a.ready.navigation.read().kind,"table");
 const row=list.rows[0],id=row.id;
 const client=createRoleMetadataClient({read:async(id,signal)=>(await (await a.transport.fetcher("/api/bo/access/roles/"+id,{signal})).json()).data,fetcher:a.transport.fetcher,idempotencyKey:a.transport.idempotencyKey});
 const edited=await client({id,expectedVersion:list.versions[id],patch:{name:"Synthetic rename"}},signal);
 assert.equal(edited.status,"saved");
 const after=await a.ready.adapter.detail(id,signal);
 assert.equal(after?.row.name,"Synthetic rename");
 assert.equal(after?.row.permissionCount,0);
 assert.equal((await b.ready.adapter.detail(id,signal))?.row.name,"Vai trò mẫu");
 const stale=await client({id,expectedVersion:list.versions[id],patch:{name:"Stale"}},signal);
 assert.equal(stale.status,"conflict");
 assert.equal((await a.transport.fetcher("https://ho.staging.pinohouse.art/api/bo/access/roles")).status,404);
 assert.equal((await a.transport.fetcher("/api/bo/access/roles/unknown")).status,404);
 assert.equal((await a.transport.fetcher("/api/ho/system/roles/"+id+"/update",{method:"POST",body:JSON.stringify({displayName:"Synthetic rename",description:after?.row.description,expectedUpdatedAt:after?.version,permissionKeys:["unregistered.permission"]})})).status,400);
 assert.equal((await a.transport.fetcher("/api/ho/system/roles/"+id+"/update",{method:"POST",body:JSON.stringify({displayName:"Synthetic rename",description:after?.row.description,expectedUpdatedAt:after?.version,permissionKeys:[rolePreviewCatalog[0].key]})})).status,200);
 const assigned=await a.ready.adapter.detail(id,signal);assert.equal(assigned?.row.permissionCount,1);
 assert.equal((await a.transport.fetcher("/api/ho/system/roles/"+id+"/archive",{method:"POST",body:JSON.stringify({expectedUpdatedAt:assigned?.version})})).status,200);
 assert.equal((await a.ready.adapter.detail(id,signal))?.row.status,"archived");
 assert.equal((await a.submitCreate({roleKey:"synthetic-other",displayName:"Other",description:null,permissionKeys:[]})).state,"verified");
 assert.equal((await a.ready.adapter.list(roleQuery,signal)).total,2);
 assert.equal((await b.ready.adapter.list(roleQuery,signal)).total,1);
});
