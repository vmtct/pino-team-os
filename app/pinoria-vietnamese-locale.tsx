function normalizePresenceTerms(input: string): string {
  return input
    .split("Vào học").join("Check-in")
    .split("vào học").join("Check-in")
    .split("Tan học").join("Check-out")
    .split("tan học").join("Check-out")
    .split("Checkout").join("Check-out")
    .split("checkout").join("Check-out");
}

function translate(input: string): string {
  const direct = exact.find(([from]) => from === input);
  let output = direct ? direct[1] : input;
  for (const [from, to] of generic) output = output.split(from).join(to);
  return normalizePresenceTerms(output);
}

function translateNode(node: Node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const value = node.nodeValue ?? "";
    const core = value.trim();
    if (!core) return;
    const next = translate(core);
    if (next !== core) node.nodeValue = value.replace(core, next);
    return;
  }
  if (!(node instanceof HTMLElement)) return;
  for (const attr of ["placeholder", "aria-label", "title"]) {
    const value = node.getAttribute(attr);
    if (value) node.setAttribute(attr, translate(value));
  }
  if (node instanceof HTMLInputElement && node.value) node.value = translate(node.value);
  if (node instanceof HTMLTextAreaElement && node.value) node.value = translate(node.value);
  node.childNodes.forEach(translateNode);
}

export function PinoriaVietnameseLocale({ children }: { children: ReactNode }) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const root = ref.current;
    if (!root) return;
    translateNode(root);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        mutation.addedNodes.forEach(translateNode);
        if (mutation.type === "characterData") translateNode(mutation.target);
      }
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true });
    return () => observer.disconnect();
  }, []);
  return <div ref={ref}>{children}</div>;
}